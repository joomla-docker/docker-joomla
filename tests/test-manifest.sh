#!/usr/bin/env bash
set -Eeuo pipefail
test_case="manifest test setup"
trap 'echo "FAIL: $test_case (${BASH_SOURCE[0]}:$LINENO)" >&2' ERR
repository="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
temporary="$(mktemp -d)"
trap 'rm -rf "$temporary"' EXIT
mkdir -p "$temporary/repository/src/build/lib" "$temporary/repository/conf" "$temporary/bin"
cp "$repository/release.sh" "$temporary/repository/"
cp "$repository/conf/maintainers.json" "$temporary/repository/conf/"
cp "$repository/src/build/lib/"*.jq "$temporary/repository/src/build/lib/"
jq --arg fixture current \
  -f "$repository/tests/fixtures.jq" "${TEST_VERSIONS_FILE:-$repository/conf/versions.json}" >"$temporary/repository/conf/versions.json"

# Stub only the metadata download; architecture parsing uses real shell code.
cat >"$temporary/bin/curl" <<'MOCK'
#!/usr/bin/env bash
set -Eeuo pipefail
printf '%s\n' "$*" >>"$PHP_METADATA_TEST_LOG"
if [[ ${PHP_METADATA_TEST_FAIL:-0} == 1 ]]; then exit 22; fi
destination=''
source_found=0
while (($#)); do
  case "$1" in
    -o) destination=$2; shift ;;
    https://raw.githubusercontent.com/docker-library/official-images/master/library/php) source_found=1 ;;
  esac
  shift
done
[[ -n $destination && $source_found == 1 ]]
cp "$PHP_METADATA_TEST_FILE" "$destination"
MOCK
chmod +x "$temporary/bin/curl"
export PATH="$temporary/bin:$PATH" PHP_METADATA_TEST_LOG="$temporary/download.log" PHP_METADATA_TEST_FILE="$temporary/php-metadata"
cd "$temporary/repository"
# Parent image names come from JSON, including configured variant overrides.
jq '
  to_entries[0].key as $series
  | (.[$series].states | to_entries[0].value.php) as $php
  | .[$series].variants[0] as $variant
  | .[$series].phpVersions[$php].variants[$variant].base += "-fixture"
' conf/versions.json >"$temporary/configured.json"
mv "$temporary/configured.json" conf/versions.json
jq -f src/build/lib/tags.jq conf/versions.json >"$temporary/plan.json"
while IFS=$'\t' read -r directory version parent development; do
  mkdir -p "$directory"
  if [[ "$development" == true ]]; then
    # Runtime metadata and files are inherited from the matching normal image.
    printf 'FROM %s\n' "$parent" >"$directory/Dockerfile"
  else
    printf 'FROM %s\nENV JOOMLA_VERSION=%s\nCOPY runtime.ini /usr/local/etc/php/conf.d/runtime.ini\n' \
      "$parent" "$version" >"$directory/Dockerfile"
    printf '; fixture\n' >"$directory/runtime.ini"
    printf '%s\n' "$parent" >>"$temporary/parents"
  fi
done < <(jq -r --slurpfile config conf/versions.json '
  .[] as $context
  | (if $context.development then
       "joomla:" + $context.version + "-php" + $context.php + "-" + $context.variant
     else $config[0][$context.series].phpVersions[$context.php].variants[$context.variant].base end) as $parent
  | [$context.directory, $context.version, $parent, $context.development] | @tsv
' "$temporary/plan.json")
while IFS= read -r parent; do
  # Different runtime parents have different architecture sets; the dev image
  # must inherit exactly the matching normal image's set without remote lookup.
  architectures='amd64,
               arm64v8'
  if [[ "$parent" == *alpine* ]]; then architectures=amd64; fi
  printf 'Tags: unrelated-%s,\n      %s\nArchitectures: %b\n\n' \
    "${parent#php:}" "${parent#php:}" "$architectures"
done < <(sort -u "$temporary/parents") >"$PHP_METADATA_TEST_FILE"
cp "$PHP_METADATA_TEST_FILE" "$temporary/valid-metadata"
mkdir -p obsolete
printf 'FROM unavailable:obsolete\n' >obsolete/Dockerfile
git init -q
git config user.name 'Manifest fixture'
git config user.email 'manifest-fixture@example.test'
git add .
git commit -qm 'Create manifest fixture'
initial_commit="$(git rev-parse HEAD)"
canonical_generator=https://github.com/joomla-docker/docker-joomla
jq -r --arg commit "$initial_commit" '.[] | .directory + " " + $commit' \
  "$temporary/plan.json" | sort >"$temporary/expected-commits"

assert_header() {
  local manifest=$1 generator=${2:-$canonical_generator} expected
  expected="# Generated by $generator/blob/$(git rev-parse HEAD)/release.sh"
  [[ "$(head -n 1 "$manifest")" == "$expected" ]]
  [[ "$(grep -c '^# Generated by ' "$manifest")" == 1 ]]
}

assert_context_commits() {
  local manifest=$1
  awk '$1 == "GitCommit:" { commit = $2 } $1 == "Directory:" { print $2 " " commit }' \
    "$manifest" | sort >"$temporary/actual-commits"
  cmp "$temporary/expected-commits" "$temporary/actual-commits"
}

update_expected_commit() {
  local changed_directory=$1
  awk -v directory="$changed_directory" -v commit="$(git rev-parse HEAD)" \
    '$1 == directory { $2 = commit } { print }' "$temporary/expected-commits" >"$temporary/updated-commits"
  mv "$temporary/updated-commits" "$temporary/expected-commits"
}

test_case="manifest tags and directories match the publication plan"
(cd /; "$temporary/repository/release.sh") >"$temporary/manifest"
jq -r '.[] | "Tags: " + (.tags | join(", "))' "$temporary/plan.json" >"$temporary/expected-tags"
grep '^Tags:' "$temporary/manifest" >"$temporary/actual-tags"
cmp "$temporary/expected-tags" "$temporary/actual-tags"
jq -r '.[] | "Directory: " + .directory' "$temporary/plan.json" >"$temporary/expected-paths"
grep '^Directory:' "$temporary/manifest" >"$temporary/actual-paths"
cmp "$temporary/expected-paths" "$temporary/actual-paths"
assert_context_commits "$temporary/manifest"
test_case="dev contexts inherit architectures from their matching normal images"
jq -r '.[] | .directory + " " + (if .variant == "fpm-alpine" then "amd64" else "amd64, arm64v8" end)' \
  "$temporary/plan.json" | sort >"$temporary/expected-architectures"
awk '$1 == "Architectures:" { sub(/^Architectures: /, ""); arches = $0 } $1 == "Directory:" { print $2 " " arches }' \
  "$temporary/manifest" | sort >"$temporary/actual-architectures"
cmp "$temporary/expected-architectures" "$temporary/actual-architectures"
test_case="manifest names the committed generator and selects BuildKit globally"
assert_header "$temporary/manifest"
[[ "$(grep -c '^Builder:' "$temporary/manifest")" == 1 ]]
grep -qx 'Builder: buildkit' "$temporary/manifest"
awk '/^Tags:/ { exit } /^Builder: buildkit$/ { found = 1 } END { exit !found }' "$temporary/manifest"
test_case="download metadata once for all parent images"
[[ "$(wc -l <"$PHP_METADATA_TEST_LOG")" == 1 ]]
grep -q '^Architectures: amd64, arm64v8$' "$temporary/manifest"

test_case="selected track honors repository and ref overrides"
# Select a configured track, regardless of whether it is stable or a prerelease.
selector="$(jq -r '.[0] | .series + "/" + .state' "$temporary/plan.json")"
directory="$(jq -r '.[0].directory' "$temporary/plan.json")"
parent="$(awk '$1 == "FROM" { print $2 }' "$directory/Dockerfile")"
version="$(jq -r '.[0].version' "$temporary/plan.json")"
STACKBREW_GIT_REPO=https://example.test/joomla.git STACKBREW_GIT_FETCH=refs/heads/test \
  ./release.sh "$selector/" >"$temporary/selected"
[[ "$(grep -c '^Directory:' "$temporary/selected")" == "$(jq --arg selector "$selector" '[.[] | select((.series + "/" + .state) == $selector)] | length' "$temporary/plan.json")" ]]
grep -q '^GitRepo: https://example.test/joomla.git$' "$temporary/selected"
grep -q '^GitFetch: refs/heads/test$' "$temporary/selected"
assert_header "$temporary/selected"
test_case="GitHub repository overrides keep the generator provenance in that repository"
for git_repo in https://github.com/manifest-fixture/joomla.git https://github.com/manifest-fixture/joomla; do
  STACKBREW_GIT_REPO="$git_repo" ./release.sh "$selector" >"$temporary/github-repository"
  grep -Fxq "GitRepo: $git_repo" "$temporary/github-repository"
  assert_header "$temporary/github-repository" https://github.com/manifest-fixture/joomla
done

reject() {
  local diagnostic="$1"; shift
  test_case="reject invalid manifest input: $diagnostic"
  if ./release.sh "$@" >"$temporary/output" 2>"$temporary/error"; then
    printf 'FAIL: expected manifest error: %s\n' "$diagnostic" >&2; exit 1
  fi
  if [[ -s "$temporary/output" ]]; then
    echo "FAIL: invalid input produced a partial manifest: $diagnostic" >&2; exit 1
  fi
  if ! grep -Fq "$diagnostic" "$temporary/error"; then
    echo "FAIL: expected diagnostic: $diagnostic; actual error follows" >&2
    cat "$temporary/error" >&2; exit 1
  fi
}
reject 'unknown release selector' unconfigured
for release_input in release.sh conf/versions.json conf/maintainers.json \
  src/build/lib/tags.jq src/build/lib/validate-config.jq; do
  printf '\n' >>"$release_input"
  reject 'uncommitted changes'
  git add "$release_input"
  reject 'uncommitted changes'
  git restore --staged --worktree -- "$release_input"
done
mv "$directory/Dockerfile" "$temporary/Dockerfile"
reject "missing $directory/Dockerfile"
mv "$temporary/Dockerfile" "$directory/Dockerfile"
printf '; changed\n' >>"$directory/runtime.ini"
reject 'uncommitted changes'
git restore -- "$directory/runtime.ini"

# Keep the two context changes in separate commits. Every other context must
# continue to name the initial snapshot, even as repository HEAD moves forward.
test_case="a Dockerfile change updates only its own context commit"
printf '# changed build instructions\n' >>"$directory/Dockerfile"
git add "$directory/Dockerfile"
git commit -qm 'Change one context Dockerfile'
update_expected_commit "$directory"
./release.sh >"$temporary/dockerfile-change"
assert_header "$temporary/dockerfile-change"
assert_context_commits "$temporary/dockerfile-change"

test_case="a copied runtime change has its own context commit"
other_directory="$(jq -er --arg directory "$directory" '[.[] | select(.development == false and .directory != $directory)][0].directory' "$temporary/plan.json")"
[[ "$other_directory" != "$directory" ]]
printf '; changed runtime settings\n' >>"$other_directory/runtime.ini"
git add "$other_directory/runtime.ini"
git commit -qm 'Change another context runtime input'
update_expected_commit "$other_directory"
./release.sh >"$temporary/copied-file"
assert_header "$temporary/copied-file"
assert_context_commits "$temporary/copied-file"

test_case="metadata and documentation advance the generator header without repinning images"
printf 'Publication fixture documentation.\n' >README.md
printf '\n' >>conf/maintainers.json
git add README.md conf/maintainers.json
git commit -qm 'Update publication metadata and documentation'
./release.sh >"$temporary/metadata-only"
assert_header "$temporary/metadata-only"
assert_context_commits "$temporary/metadata-only"
[[ "$(head -n 1 "$temporary/metadata-only")" != "$(head -n 1 "$temporary/copied-file")" ]]

test_case="shallow history cannot identify the latest changes to each context"
git -c protocol.file.allow=always clone --quiet --depth=1 \
  "file://$temporary/repository" "$temporary/shallow-repository"
(cd "$temporary/shallow-repository"; reject 'shallow')
for architectures in '' '   ' unrecognised; do
  printf 'Tags: %s\nArchitectures: %s\n' "${parent#php:}" "$architectures" >"$PHP_METADATA_TEST_FILE"
  reject 'architecture'
done
printf 'Tags: unknown-tag\nArchitectures: amd64\n' >"$PHP_METADATA_TEST_FILE"
reject 'missing or ambiguous architecture'
cp "$temporary/valid-metadata" "$PHP_METADATA_TEST_FILE"
printf 'Tags: %s\nArchitectures: amd64\n' "${parent#php:}" >>"$PHP_METADATA_TEST_FILE"
reject 'missing or ambiguous architecture'
cp "$temporary/valid-metadata" "$PHP_METADATA_TEST_FILE"
export PHP_METADATA_TEST_FAIL=1
reject 'could not download PHP architecture metadata'
unset PHP_METADATA_TEST_FAIL

# A dev context cannot silently switch to another release, PHP, runtime, or
# redefine the version that its official Joomla parent supplies.
dev_directory="$(jq -er '[.[] | select(.development)][0].directory' "$temporary/plan.json")"
cp "$dev_directory/Dockerfile" "$temporary/dev-Dockerfile"
for invalid_parent in joomla:100.0.0-php100.0-fpm php:100.0-fpm; do
  printf 'FROM %s\n' "$invalid_parent" >"$dev_directory/Dockerfile"
  git add "$dev_directory/Dockerfile"
  git commit -qm 'Change dev parent incorrectly'
  reject 'expected joomla:'
done
cp "$temporary/dev-Dockerfile" "$dev_directory/Dockerfile"
printf 'ENV JOOMLA_VERSION=100.0.0\n' >>"$dev_directory/Dockerfile"
git add "$dev_directory/Dockerfile"
git commit -qm 'Override inherited dev version incorrectly'
reject 'inherit'
cp "$temporary/dev-Dockerfile" "$dev_directory/Dockerfile"
git add "$dev_directory/Dockerfile"
git commit -qm 'Restore dev parent'

for instruction in $'COPY \\\n  --from=external:test /tool /tool' \
    $'RUN \\\n  --mount=type=bind,from=external:test,target=/tools true' 'FROM unknown:test'; do
  printf 'FROM %s\nENV JOOMLA_VERSION=%s\n%s\n' "$parent" "$version" "$instruction" >"$directory/Dockerfile"
  git add "$directory/Dockerfile"
  git commit -qm 'Create an unsupported dependency fixture'
  reject 'unsupported image dependencies'
done
printf 'Manifest generation tests passed.\n'
